"""Deterministic Cypher AST & Schema Whitelist Guardrail.

Enforces strict read-only execution, schema conformity, and property whitelisting
on openCypher queries generated by yarnball-qwen:7b or external callers.
Prevents execution of hallucinated schema properties (e.g. 'ceo_age', 'sc_3_carbon_emissions').
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Set, Tuple


@dataclass
class SchemaViolation:
    """Represents a specific violation detected in a Cypher query."""

    violation_type: str  # 'UNKNOWN_PROPERTY', 'UNKNOWN_LABEL', 'UNKNOWN_REL_TYPE', 'MUTATING_KEYWORD', 'ADMIN_PROCEDURE'
    identifier: str
    message: str


@dataclass
class ValidationResult:
    """Result of Cypher query validation."""

    is_valid: bool
    sanitized_query: Optional[str]
    violations: List[SchemaViolation] = field(default_factory=list)
    refusal_response: str = "(none)"

    @property
    def error_summary(self) -> Optional[str]:
        if not self.violations:
            return None
        return "; ".join(v.message for v in self.violations)


@dataclass
class SchemaSpecification:
    """Whitelisted graph schema definition."""

    allowed_labels: Set[str] = field(default_factory=set)
    allowed_rel_types: Set[str] = field(default_factory=set)
    allowed_properties: Set[str] = field(default_factory=set)
    case_sensitive: bool = False

    def is_label_allowed(self, label: str) -> bool:
        if self.case_sensitive:
            return label in self.allowed_labels
        return label.lower() in {lbl.lower() for lbl in self.allowed_labels}

    def is_rel_type_allowed(self, rel_type: str) -> bool:
        if self.case_sensitive:
            return rel_type in self.allowed_rel_types
        return rel_type.lower() in {rel.lower() for rel in self.allowed_rel_types}

    def is_property_allowed(self, prop: str) -> bool:
        if self.case_sensitive:
            return prop in self.allowed_properties
        return prop.lower() in {p.lower() for p in self.allowed_properties}



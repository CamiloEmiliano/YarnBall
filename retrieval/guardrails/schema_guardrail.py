class CypherASTWhitelistGuardrail:
    """Validates openCypher statements against allowed schemas and safety invariants."""

    def __init__(
        self,
        schema: Optional[SchemaSpecification] = None,
        max_limit: int = 100,
        refuse_on_unknown_property: bool = True,
        refuse_on_unknown_label: bool = False,
    ):
        self.schema = schema or DEFAULT_FINANCE_SCHEMA
        self.max_limit = max_limit
        self.refuse_on_unknown_property = refuse_on_unknown_property
        self.refuse_on_unknown_label = refuse_on_unknown_label

    def validate(self, cypher: str) -> ValidationResult:
        """Validate Cypher query for syntax, mutations, labels, and property whitelist."""
        if not cypher or not cypher.strip():
            return ValidationResult(
                is_valid=False,
                sanitized_query=None,
                violations=[
                    SchemaViolation("EMPTY_QUERY", "", "Generated Cypher query is empty.")
                ],
                refusal_response="(none)",
            )

        clean = cypher.strip()

        # 1. Strip comments and string literals to prevent matching inside quotes
        masked_query, string_literals = self._mask_literals_and_comments(clean)

        # 2. Check for mutating keywords (CREATE, MERGE, DELETE, SET, etc.)
        words = set(re.findall(r"\b[A-Z_]+\b", masked_query.upper()))
        forbidden_matches = words.intersection(FORBIDDEN_MUTATING_KEYWORDS)
        if forbidden_matches:
            violations = [
                SchemaViolation(
                    "MUTATING_KEYWORD",
                    kw,
                    f"Mutating operations forbidden in read-only query: '{kw}'",
                )
                for kw in sorted(list(forbidden_matches))
            ]
            return ValidationResult(
                is_valid=False,
                sanitized_query=None,
                violations=violations,
                refusal_response="(none)",
            )

        # 3. Check administrative procedures (CALL DBMS, CALL MG., etc.)
        upper_query = masked_query.upper()
        for proc in FORBIDDEN_PROCEDURE_PREFIXES:
            if proc in upper_query:
                return ValidationResult(
                    is_valid=False,
                    sanitized_query=None,
                    violations=[
                        SchemaViolation(
                            "ADMIN_PROCEDURE",
                            proc,
                            f"Administrative procedure call is forbidden: '{proc}'",
                        )
                    ],
                    refusal_response="(none)",
                )

        # 4. Basic structural start check for read-only queries
        if not re.match(r"^(MATCH|WITH|UNWIND|RETURN|CALL)\b", clean, re.IGNORECASE):
            return ValidationResult(
                is_valid=False,
                sanitized_query=None,
                violations=[
                    SchemaViolation(
                        "INVALID_START",
                        clean[:20],
                        f"Query must begin with MATCH, WITH, UNWIND, or RETURN. Got: '{clean[:20]}...'",
                    )
                ],
                refusal_response="(none)",
            )

        violations: List[SchemaViolation] = []

        # 5. Extract and validate node labels and relationship types
        labels, rel_types = self._extract_labels_and_rels(masked_query)

        for lbl in labels:
            if not self.schema.is_label_allowed(lbl):
                v = SchemaViolation(
                    "UNKNOWN_LABEL",
                    lbl,
                    f"Node label ':{lbl}' is not in the allowed schema.",
                )
                if self.refuse_on_unknown_label:
                    violations.append(v)

        for rel in rel_types:
            if not self.schema.is_rel_type_allowed(rel):
                v = SchemaViolation(
                    "UNKNOWN_REL_TYPE",
                    rel,
                    f"Relationship type '[:{rel}]' is not in the allowed schema.",
                )
                if self.refuse_on_unknown_label:
                    violations.append(v)

        # 6. Extract and validate properties (dot-access and map literals)
        referenced_properties = self._extract_properties(masked_query)

        for prop in referenced_properties:
            if not self.schema.is_property_allowed(prop):
                violations.append(
                    SchemaViolation(
                        "UNKNOWN_PROPERTY",
                        prop,
                        f"Property '{prop}' does not exist in graph schema.",
                    )
                )

        # If any violations found
        if violations:
            refusal_msg = "(none)"
            if any(v.violation_type == "UNKNOWN_PROPERTY" for v in violations):
                bad_props = [v.identifier for v in violations if v.violation_type == "UNKNOWN_PROPERTY"]
                refusal_msg = f"(none) // REFUSED: non-existent schema properties: {sorted(list(bad_props))}"

            return ValidationResult(
                is_valid=False,
                sanitized_query=None,
                violations=violations,
                refusal_response=refusal_msg,
            )

        # 7. Apply bounded LIMIT enforcement
        clamped_query = self.enforce_limit(clean)

        return ValidationResult(
            is_valid=True,
            sanitized_query=clamped_query,
            violations=[],
            refusal_response="",
        )

    def enforce_limit(self, cypher: str) -> str:
        """Ensure the Cypher query contains a bounded LIMIT clause."""
        clean = cypher.strip().rstrip(";")
        limit_match = re.search(r"\bLIMIT\s+(\d+)", clean, re.IGNORECASE)

        if limit_match:
            current_limit = int(limit_match.group(1))
            if current_limit > self.max_limit:
                clean = re.sub(
                    r"\bLIMIT\s+\d+",
                    f"LIMIT {self.max_limit}",
                    clean,
                    flags=re.IGNORECASE,
                )
        else:
            clean = f"{clean} LIMIT {self.max_limit}"

        return clean

    def _mask_literals_and_comments(self, cypher: str) -> Tuple[str, List[str]]:
        """Mask single/double quoted string literals and comments."""
        literals: List[str] = []

        # Strip line comments: // ...
        text = re.sub(r"//.*$", "", cypher, flags=re.MULTILINE)
        # Strip block comments: /* ... */
        text = re.sub(r"/\*.*?\*/", "", text, flags=re.DOTALL)

        def _sub_literal(m: re.Match) -> str:
            literals.append(m.group(0))
            return f"__STR_LIT_{len(literals)-1}__"

        # Mask string literals: '...' or "..."
        masked = re.sub(r"'(?:\\.|[^'\\])*'|\"(?:\\.|[^\"\\])*\"", _sub_literal, text)
        return masked, literals

    def _extract_labels_and_rels(self, masked_query: str) -> Tuple[Set[str], Set[str]]:
        """Extract node labels and relationship types from Cypher pattern expressions."""
        labels: Set[str] = set()
        rels: Set[str] = set()

        # Extract node patterns: (:Label) or (var:Label) or (:Label1:Label2)
        node_matches = re.findall(r"\([a-zA-Z0-9_]*:([a-zA-Z0-9_|:]+)\)", masked_query)
        for group in node_matches:
            for lbl in re.split(r"[:|]", group):
                lbl_clean = lbl.strip()
                if lbl_clean and not lbl_clean.startswith("__STR_LIT"):
                    labels.add(lbl_clean)

        # Extract relationship patterns: [:TYPE] or [var:TYPE] or [:TYPE1|TYPE2]
        rel_matches = re.findall(r"\[[a-zA-Z0-9_]*:([a-zA-Z0-9_|*.]+)\s*(\{[^}]*\})?\]", masked_query)
        for group, _ in rel_matches:
            # Strip variable hop ranges: e.g. *1..3
            type_part = re.sub(r"\*[0-9.]*", "", group)
            for r_type in type_part.split("|"):
                r_clean = r_type.strip()
                if r_clean and not r_clean.startswith("__STR_LIT"):
                    rels.add(r_clean)

        return labels, rels

    def _extract_properties(self, masked_query: str) -> Set[str]:
        """Extract property keys accessed via dot notation (var.prop) or map literals {prop: val}."""
        properties: Set[str] = set()

        # 1. Dot-access: <var>.<property> (e.g. c.ceo_age, r.status, s.sc_3_carbon_emissions)
        # Exclude parameters ($as_of_date) and function calls (apoc.math.round)
        dot_matches = re.findall(r"(?<!\$)\b([a-zA-Z_][a-zA-Z0-9_]*)\.([a-zA-Z_][a-zA-Z0-9_]*)\b", masked_query)
        for var_name, prop_name in dot_matches:
            # Check if this is a function call like `toLower(var.prop)` vs namespace `date.truncate`
            if var_name.lower() in BUILTIN_FUNCTIONS_AND_NAMESPACES:
                continue
            if prop_name.startswith("__STR_LIT"):
                continue
            properties.add(prop_name)

        # 2. Map literals: {ticker: 'AAPL', status: 'ACTIVE_CURRENT'}
        map_matches = re.findall(r"\{([^{}]+)\}", masked_query)
        for map_body in map_matches:
            for pair in map_body.split(","):
                if ":" in pair:
                    key = pair.split(":", 1)[0].strip()
                    if key and re.match(r"^[a-zA-Z_][a-zA-Z0-9_]*$", key):
                        if not key.startswith("__STR_LIT"):
                            properties.add(key)

        return properties
